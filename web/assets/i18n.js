function storedLang() {
  try { return localStorage.getItem(STORAGE_KEY); } catch { return null; }
}

function writeCookie(value) {
  document.cookie = `fev_lang=${value}; path=/; max-age=31536000; SameSite=Strict`;
}

export const lang = LANGS.includes(storedLang()) ? storedLang() : 'en';
export const locale = lang === 'fr' ? 'fr-FR' : 'en-US';
document.documentElement.lang = lang;
writeCookie(lang);

/** Traduit une clé ; {param} est remplacé, et `count` choisit la forme singulière (clé `_one`). */
export function t(key, params = {}) {
  const dict = DICT[lang];
  let k = key;
  if (typeof params.count === 'number') {
    const singular = lang === 'fr' ? params.count < 2 : params.count === 1;
    if (singular && (`${key}_one` in dict)) k = `${key}_one`;
  }
  const text = dict[k] ?? DICT.en[k] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (params[name] !== undefined ? params[name] : m));
}

/** Change de langue : mémorise le choix, prévient le serveur et recharge la page. */
export function setLang(value) {
  if (!LANGS.includes(value)) return;
  try { localStorage.setItem(STORAGE_KEY, value); } catch { /* navigation privée */ }
  writeCookie(value);
  location.reload();
}

/** Textes statiques de index.html : data-i18n (texte), data-i18n-title (infobulle et aria-label). */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => { node.textContent = t(node.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((node) => {
    node.title = t(node.dataset.i18nTitle);
    node.setAttribute('aria-label', t(node.dataset.i18nTitle));
  });
  root.querySelectorAll('[data-i18n-label]').forEach((node) => { node.setAttribute('aria-label', t(node.dataset.i18nLabel)); });
}

